-- ============================================================================
-- 20261023000000_001_wecom_daily_order_list_limit —— 第三节「按交期分组的工单清单」
--   的两个配置项（order_list_limit / include_drawings）
-- ============================================================================
-- 背景（用户原话，2026-10-23）：第三节从「逾期 N 单 / 3 日内交期 N 单」两个计数
--   改成**按交期日期分组的工单清单**（含图纸链接）。清单形态必须有两个可配的量，
--   否则要么把清单撑爆（分片装不下 → 21804），要么把链接全带上（每行多 95 字节）。
--
-- 归属域：`src/modules/wecom_daily/`（内容域）。**append-only 追加**，不改
--   `20261018000000_001_wecom.sql` 任何一行。
--
-- 与本仓既有约定的关系（全部照 CLAUDE.md「DB 约定」）：
--   * 无物理外键 / 无 DB ENUM —— 两列都是标量，无引用、无取值域。
--   * NOT NULL + DEFAULT —— 与本表其余可配列同款：读侧永远不必处理 NULL，
--     存量行由 DEFAULT 补齐（③ 下面登记了为什么 DEFAULT 选 30 / true）。
--   * 雪花主键 / 乐观锁 / 软删与本表其它列一致，本迁移不碰。
--
-- ⚠️ **本迁移只落「配置」，不落「渲染」**：第三节的清单渲染是另一轮改造的内容。
--   两列先入库、后接渲染，接渲染那一轮不需要再改表结构（append-only 迁移的
--   好处正在这里）。
-- ============================================================================

ALTER TABLE public.t_wecom_daily_config
    ADD COLUMN order_list_limit integer NOT NULL DEFAULT 30,
    ADD COLUMN include_drawings boolean NOT NULL DEFAULT true;

-- ⚠️ **取值域 `0..=200`，与 `worker_top_n` 同款**（0 = 不限）。为什么要有 200 这个
--   上界：清单是**逐行**渲染的，一条工单一行，上限防的是「把一个月的交期一次性
--   拉出来」这种配置 —— 那种配置在分片装填阶段会以 21804 失败（而不是被静默截断），
--   但让人在**保存配置时**就知道自己填了多大的量，比在推送时才发现省事。
COMMENT ON COLUMN public.t_wecom_daily_config.order_list_limit IS
    '第三节交期工单清单每组最多列出的工单数；0 = 不限（与 worker_top_n 的 0 同语义）；取值域 0..200，保存时 clamp、合并覆盖时越界 → 21804';

-- ⚠️ **默认 true 而不是 false**：图纸链接是这一节存在的**主要理由**（用户要的就是
--   「点进去能看到图」）。默认关掉的话，装上就发现清单里没有链接的管理员会先去
--   配一遍，而不是意识到它可配。
COMMENT ON COLUMN public.t_wecom_daily_config.include_drawings IS
    '第三节清单是否带图纸预览直链；true = 带（约 95 字节/行），false = 只列图号与工单号';
