-- 2026-10-08：送货单「套数」语义补齐 DB 列注释
-- ============================================================================
-- 背景：装配件「送几套」的两个分母 / 分子此前只有 Rust 侧注释，入单对话框要把它
-- 变成用户可见的规则（装配件每套需 N 件/套），先把 schema 层的口径写进列注释，
-- 使 `psql \d` / 任意 BI 工具 / 后续 reviewer 都能看到同一份定义。
--
-- 只写 COMMENT，不改列类型 / 约束 / 默认值 ⇒ 可重复执行、无数据迁移、无锁表风险。

COMMENT ON COLUMN public.t_assembly.quantity IS
  '工单总套数（送几套）；每个子零件每套的需求量 = t_part.quantity / 本列';

COMMENT ON COLUMN public.t_part.quantity IS
  '单个子零件的总需求数（跨该工单的全部批次求和），不是单批次数量';