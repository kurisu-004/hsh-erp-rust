-- ============================================================================
-- 20261023010000_001_wecom_daily_note_count_semantics —— 第二节那个数改由
--   `note_count` 一键承载，`note_part_count` 下线
-- ============================================================================
-- 背景：第二节从「今日出货单数 + 出货件数」两个计数改成**单一**数字（本期出货的
--   去重工单数）。`t_wecom_daily_log` 上原本有两列承载它：`note_count`（送货单
--   张数）与 `note_part_count`（出货工单数）。两个键表达同一个数字会让读流水的人
--   必须先搞清哪个才是现在那个；而往一条只增的审计流水里把 `note_count` 写死成 0
--   等于把「今天没有送货单」记成事实，是谎话。
--
-- 故本迁移：**删掉 `note_part_count`，并把 `note_count` 的语义换成它**
-- （本期出货的去重工单数）。
--
-- 归属域：`src/modules/wecom_daily/`（内容域）。**append-only 追加**，不改
--   `20261018000000_001_wecom.sql` 与 `20261023000000_001_…` 任何一行。
--
-- 与本仓既有约定的关系（全部照 CLAUDE.md「DB 约定」）：
--   * 无物理外键 / 无 DB ENUM —— 本迁移只动一个标量列的注释与删一列。
--   * 迁移 append-only：既有迁移不改写，语义变更以本次的 COMMENT 登记。
-- ============================================================================

-- ⚠️ **直接删列、不加过渡列**：流水表只增不删行、也没有 UPDATE 路径，历史行的
--   `note_part_count` 只在被 GET /logs 读出时才需要；而那个读出路径与出参同步
--   下线（本轮 Rust 侧同步删字段），留着列只会让「表里有、接口里没有」的差异长期
--   悬着，下一个读表结构的人必然重新困惑一次。
ALTER TABLE public.t_wecom_daily_log DROP COLUMN note_part_count;

-- ⚠️ **历史行按旧语义理解**：本迁移不改任何存量行的值 ⇒ 迁移日之前落下的行，
--   `note_count` 里记的是**送货单张数**（不是去重工单数）。两者数量级可能完全不同
--   （一单多件时前者远小于后者），且旧行当时的 `note_part_count` 已随列删除而不复
--   存在。要读历史流水只能按这个语义读；日报正文里的这个数字请只看当前推送。
COMMENT ON COLUMN public.t_wecom_daily_log.note_count IS
    '本期出货的去重工单数（COUNT(DISTINCT part_id)，第二节的那个数）。⚠️ 2026-10-23 之前该列记的是「本期出货的送货单张数」，历史行按旧语义理解';
